package com.github.jinahya.postgresql.demodb.data;

import com.github.jinahya.postgresql.demodb.persistence.Flight;
import com.github.jinahya.postgresql.demodb.persistence.Flight_;
import jakarta.persistence.Tuple;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.repository.Query;
import org.springframework.stereotype.Repository;

import java.time.OffsetDateTime;
import java.util.List;

/**
 * A repository for {@link Flight}, the {@code flights} table of the demonstration database.
 * <p>
 * The id is an {@link Integer} generated by the database ({@code GENERATED ALWAYS AS IDENTITY}), the only generated
 * id of the schema, so a new flight is saved with no id, and the id is set on the saved instance. The methods below
 * answer the exercises of upstream's {@code EXERCISES.asciidoc} on the {@code flights} table, one method per
 * exercise, named in each method's javadoc by the exercise's id ({@code DEMODB_FLIGHTS_B_01}, ...). A Basic exercise
 * is a derived query, with the order the exercise asks for in its name, and returns a {@link List}, with no
 * {@link Pageable}. An Intermediate one takes a {@link Pageable}, the page, and returns a {@link Page}; the order the
 * exercise asks for is in the query, and its {@code LIMIT} is the size of the caller's page. A result that is not an
 * entity comes back as a {@link jakarta.persistence.Tuple}, each element read by its alias, with its type.
 *
 * @see Flight
 * @see Flight_
 */
@Repository
public interface FlightRepository
        extends _Repository<Flight, Integer> {

    // ----------------------------------------------------------------------------------------------------- exercises

    /**
     * Finds the flights of the specified route scheduled to depart in the specified half-open interval, by
     * {@link Flight_#SCHEDULED_DEPARTURE} ({@code DEMODB_FLIGHTS_B_01}, which asks for the flights of {@code PG0001}
     * in October 2025, from {@code 2025-10-01} inclusive to {@code 2025-11-01} exclusive, ordered by
     * {@link Flight_#SCHEDULED_DEPARTURE}).
     * <p>
     * The query, and its order, are derived from the method name. The exercise lists the matches whole, so there is
     * no {@link Pageable}.
     *
     * @param routeNo the value of the {@link Flight_#ROUTE_NO} attribute to match; must not be {@code null}.
     * @param from    the lower bound of the {@link Flight_#SCHEDULED_DEPARTURE}, inclusive; must not be {@code null}.
     * @param to      the upper bound of the {@link Flight_#SCHEDULED_DEPARTURE}, exclusive; must not be {@code null}.
     * @return a list of the flights of {@code routeNo} scheduled to depart in {@code [from, to)}, by scheduled
     *         departure; empty if there is none.
     */
    List<Flight> findAllByRouteNoAndScheduledDepartureGreaterThanEqualAndScheduledDepartureLessThanOrderByScheduledDepartureAsc(
            String routeNo, OffsetDateTime from, OffsetDateTime to);

    /**
     * Selects each month with how many flights are scheduled to depart in it ({@code DEMODB_FLIGHTS_I_01}, which
     * orders by the month; the exercise shows every row, so the caller's page holds them all).
     * <p>
     * The year and the month are taken out of the {@link Flight_#SCHEDULED_DEPARTURE} with {@code EXTRACT}, in the
     * session's time zone, and the flights are grouped by the two and counted. The count query counts the distinct
     * months through the same expressions.
     *
     * @param pageable the page to return; must not be {@code null}.
     * @return a page of the months with their numbers of flights, each a tuple of {@code year} and {@code month}
     *         ({@link Integer}s) and {@code flights} ({@link Long}).
     */
    @Query(value = """
            SELECT EXTRACT(YEAR FROM f.scheduledDeparture) AS year,
                   EXTRACT(MONTH FROM f.scheduledDeparture) AS month,
                   COUNT(f) AS flights
            FROM Flight f
            GROUP BY EXTRACT(YEAR FROM f.scheduledDeparture), EXTRACT(MONTH FROM f.scheduledDeparture)
            ORDER BY EXTRACT(YEAR FROM f.scheduledDeparture), EXTRACT(MONTH FROM f.scheduledDeparture)""",
           countQuery = """
                   SELECT COUNT(DISTINCT EXTRACT(YEAR FROM f.scheduledDeparture) * 100
                                         + EXTRACT(MONTH FROM f.scheduledDeparture))
                   FROM Flight f""")
    Page<Tuple> selectFlightCountsByMonth(Pageable pageable);
}
